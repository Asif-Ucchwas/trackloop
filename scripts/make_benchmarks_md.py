"""Write BENCHMARKS.md from the Monte Carlo results (Task 16).

Every number in the file comes from data/results/mc_summary.csv, mc_pairs.csv and
mc_settings.json; the explanatory text is in this script. Run it again after the results change.
"""
import csv
import json
from pathlib import Path

RESULTS = Path("data/results")
SCOPE_TITLE = {"all": "all paths", "drivable": "drivable paths only (curvature and lateral acceleration within limits)"}


def read(path):
    return list(csv.DictReader(open(path)))


def f(x):
    return float(x)


def pm(mean, half):
    return f"{f(mean):.4f} +- {f(half):.4f}"


def speed_table(rows):
    """Markdown table: one row per controller, one column per design speed, 'mean +- half-width'."""
    speeds = sorted({f(r["speed"]) for r in rows})
    out = ["| controller | " + " | ".join(f"{v:g} m/s" for v in speeds) + " |",
           "|---|" + "---|" * len(speeds)]
    for c in dict.fromkeys(r["controller"] for r in rows):
        cells = []
        for v in speeds:
            r = next((x for x in rows if x["controller"] == c and f(x["speed"]) == v), None)
            cells.append(pm(r["mean_rms"], r["half_width"]) if r else "-")
        out.append(f"| {c} | " + " | ".join(cells) + " |")
    return out


def pair_table(pairs, summary):
    """Markdown table of paired differences a - b, with the size relative to b's mean RMS."""
    mean_b = {(r["scope"], r["controller"], f(r["speed"])): f(r["mean_rms"]) for r in summary}
    out = ["| a - b | m/s | difference +- half-width (m) | relative to b | interval excludes 0 |",
           "|---|---|---|---|---|"]
    for p in pairs:
        rel = f(p["difference"]) / mean_b[(p["scope"], p["b"], f(p["speed"]))]
        out.append(f"| {p['a']} - {p['b']} | {f(p['speed']):g} | {pm(p['difference'], p['half_width'])} "
                   f"| {rel:+.1%} | {'yes' if p['excludes_zero'] in ('True', True) else 'no'} |")
    return out


def seeds_text(n):
    if isinstance(n, dict):
        return ", ".join(f"{k} {v}" for k, v in n.items())
    return str(n)


def render(summary, pairs, cfg):
    families = list(dict.fromkeys(r["family"] for r in summary))
    unfinished = sum(int(f(r["runs"])) - int(f(r["finished"])) for r in summary if r["scope"] == "all")
    total = sum(int(f(r["runs"])) for r in summary if r["scope"] == "all")
    missing = [r for r in summary if r["meets_target"] in ("False", False)]
    worst = max(f(r["rel_half_width"]) for r in summary)
    mean_b = {(r["family"], r["scope"], r["controller"], f(r["speed"])): f(r["mean_rms"]) for r in summary}
    excluding = sum(p["excludes_zero"] in ("True", True) for p in pairs)
    smallest = min(abs(f(p["difference"])) / mean_b[(p["family"], p["scope"], p["b"], f(p["speed"]))] for p in pairs)
    L = ["# Benchmarks", "",
         f"Controller comparison with confidence intervals. Generated by `scripts/make_benchmarks_md.py` from "
         f"`data/results/mc_summary.csv`, `mc_pairs.csv` and `mc_settings.json`; the results were produced at "
         f"commit `{cfg['git_commit'][:7]}` (clean tree: {not cfg['git_dirty']}).", "",
         "## What was measured", "",
         "- Nominal plant, every controller on every frozen path of its family at its design speeds.",
         f"- Seeds per family: {seeds_text(cfg['n_seeds'])}. A seed fixes a start offset and heading error "
         "on each path (the same for every controller). The paths are a fixed set, so results hold for these paths.",
         "- Quantity: RMS lateral error at the rear axle (metres). Each seed gives one number per controller and "
         "speed, the mean over that family's paths; the tables give the mean over seeds and a 95 percent Student t "
         f"half-width over seeds. {total} runs, {unfinished} did not finish.",
         f"- Sizing rule: seeds were chosen so every cell's half-width is within {cfg['target_rel_half_width']:.0%} of "
         f"its mean. Largest achieved: {worst:.1%}; cells missing the target: {len(missing)} of {len(summary)}. "
         "The sizing used the spread seen in the 5-seed benchmark. The first full run used 120 seeds for both "
         "families; four road cells (dynamic LQR and MPC at 10 and 20 m/s) were at 5.1 to 5.4 percent, so the "
         "road family was rerun with 150 seeds.",
         "- Differences between controllers are taken seed by seed (same starts), which removes the start-to-start "
         "variation they share, so they are much tighter than the intervals on the means.", ""]
    for fam in families:
        rows = [r for r in summary if r["family"] == fam]
        L += [f"## {fam.capitalize()} family: RMS lateral error, mean +- 95% half-width (m)", ""]
        for scope in dict.fromkeys(r["scope"] for r in rows):
            if len(set(r["scope"] for r in rows)) > 1:
                L += [f"**{SCOPE_TITLE[scope]}**", ""]
            L += speed_table([r for r in rows if r["scope"] == scope]) + [""]
        for scope in dict.fromkeys(r["scope"] for r in rows):
            ps = [p for p in pairs if p["family"] == fam and p["scope"] == scope]
            if len(set(r["scope"] for r in rows)) > 1:
                L += [f"Paired differences, {SCOPE_TITLE[scope]}", ""]
            else:
                L += [f"Paired differences ({fam})", ""]
            L += pair_table(ps, rows) + [""]
        L += ["A negative difference means a has the lower error.", ""]
    L += ["## How to read these, and what they do not say", "",
          f"- **Statistically distinguishable is not the same as important.** With this many seeds {excluding} of "
          f"{len(pairs)} paired differences exclude zero, the smallest being {smallest:.1%} of the error. "
          "Look at the relative column.",
          "- **The intervals cover seed-to-seed variation only**, on these paths and with the placeholder vehicle and "
          "tolerance values. They do not cover controller tuning, a different vehicle, or different start ranges.",
          "- **Means, not medians.** Earlier notes (`benchmark_road_note.md`) quote medians over runs. They can differ "
          "from the means here: the dynamic LQR at 20 m/s has a median of 0.034 m and a mean of 0.045 m, which suggests "
          "a tail of worse runs (not examined).",
          "- **The 20 m/s road numbers for the dynamic LQR and MPC are partly outside the linear tire model's range** "
          "(front slip above the friction-limit angle in 10 of 20 runs for the LQR and 5 of 20 for the MPC in the "
          "5-seed benchmark on the nominal plant, counted again with each model-error case in "
          "`docs/notes/root_cause_note.md`, section 5). See also `docs/notes/benchmark_road_note.md`.",
          "- **Pure Pursuit and Stanley were not tuned for the road speeds.** I have not checked that their settings "
          "are fair at 20 m/s, so the size of the gap to the LQR and MPC there is not yet a statement about the "
          "controllers' designs.",
          "- **Causes are given only where they were tested.** The worst runs (the Kinematic MPC's and the road MPC's "
          "failures under steering lag, the worst start on `road_curve_v20`, Stanley's chatter at 5 m/s) are explained "
          "in `docs/notes/root_cause_note.md`, with what each test does and does not show. No cause is claimed for any "
          "other difference in this file.", ""]
    return "\n".join(L)


def main():
    summary, pairs = read(RESULTS / "mc_summary.csv"), read(RESULTS / "mc_pairs.csv")
    cfg = json.load(open(RESULTS / "mc_settings.json"))
    Path("BENCHMARKS.md").write_text(render(summary, pairs, cfg))
    print("wrote BENCHMARKS.md")


if __name__ == "__main__":
    main()
